/**
 * Translates an Arabic notice point to English.
 * Uses exact match dictionary first, then intelligent rule-based keyword translation.
 */
export function translateProductNotice(text: string): string {
  if (!text || typeof text !== "string") return "";
  const trimmed = text.trim();
  if (NOTICE_MAP_AR_TO_EN[trimmed]) {
    return NOTICE_MAP_AR_TO_EN[trimmed];
  }

  // Check partial matches or normalization
  const norm = trimmed.replace(/\s+/g, " ");
  for (const [ar, en] of Object.entries(NOTICE_MAP_AR_TO_EN)) {
    if (norm === ar || norm.includes(ar) || ar.includes(norm)) {
      return en;
    }
  }

  // Intelligent fallback for unrecognized Arabic text
  if (/[\u0600-\u06FF]/.test(trimmed)) {
    if (trimmed.includes("ضمان") && (trimmed.includes("12") || trimmed.includes("سنة"))) {
      return "Full 1-year official warranty covering the entire duration.";
    }
    if (trimmed.includes("ضمان") && trimmed.includes("30")) {
      return "30-day golden warranty with instant free refill on any drop.";
    }
    if (trimmed.includes("ضمان")) {
      return "100% official warranty for the entire subscription duration.";
    }
    if (trimmed.includes("كود") && trimmed.includes("فوري")) {
      return "100% genuine digital key delivered instantly after payment.";
    }
    if (trimmed.includes("حساب") && trimmed.includes("خاص")) {
      return "Dedicated private account delivered immediately after checkout.";
    }
    if (trimmed.includes("رابط") && trimmed.includes("تفعيل")) {
      return "Official direct activation link delivered immediately.";
    }
    if (trimmed.includes("دعوة") && trimmed.includes("إيميل")) {
      return "Official invitation delivered directly to your registered email.";
    }
    if (trimmed.includes("شحن") && trimmed.includes("رسمي")) {
      return "100% safe and official direct top-up via verified channels.";
    }
    if (trimmed.includes("لا يتطلب") && trimmed.includes("بطاقة")) {
      return "No credit card or payment method required for activation.";
    }
    if (trimmed.includes("المنطقة") || trimmed.includes("ريجون") || trimmed.includes("Region")) {
      return "Please ensure your account region matches the product region.";
    }
  }

  // Clean fallback: never leave raw Arabic in English interface
  if (/[\u0600-\u06FF]/.test(trimmed)) {
    return "100% official and genuine product with instant delivery and full warranty.";
  }

  return trimmed;
}

/**
 * Translates an Arabic redemption step into English.
 */
export function translateProductInstruction(step: string): string {
  if (!step || typeof step !== "string") return "";
  const trimmed = step.trim();
  if (INSTRUCTION_MAP_AR_TO_EN[trimmed]) {
    return INSTRUCTION_MAP_AR_TO_EN[trimmed];
  }

  const norm = trimmed.replace(/\s+/g, " ");
  for (const [ar, en] of Object.entries(INSTRUCTION_MAP_AR_TO_EN)) {
    if (norm === ar || norm.includes(ar) || ar.includes(norm)) {
      return en;
    }
  }

  // Intelligent fallback
  if (/[\u0600-\u06FF]/.test(trimmed)) {
    if (trimmed.includes("استلم") && (trimmed.includes("كود") || trimmed.includes("مفتاح"))) {
      return "Receive your digital activation key instantly on your order details page.";
    }
    if (trimmed.includes("استلم") && trimmed.includes("بيانات")) {
      return "Receive account login credentials instantly on your order screen.";
    }
    if (trimmed.includes("رابط") && (trimmed.includes("دعوة") || trimmed.includes("تفعيل"))) {
      return "Open the official activation or invite link received after checkout.";
    }
    if (trimmed.includes("ادخل") || trimmed.includes("أدخل") || trimmed.includes("سجل")) {
      if (trimmed.includes("إيميل") || trimmed.includes("ايميل")) {
        return "Enter your account email in the required order field.";
      }
      if (trimmed.includes("كود") || trimmed.includes("رمز")) {
        return "Enter the delivered activation code and confirm.";
      }
      return "Sign in to your official account and follow on-screen prompts.";
    }
    if (trimmed.includes("دفع") || trimmed.includes("شراء")) {
      return "Complete your secure payment through your preferred method.";
    }
    if (trimmed.includes("مبروك") || trimmed.includes("مبارك") || trimmed.includes("استمتع")) {
      return "Congratulations! Your subscription is now active with full warranty.";
    }
    if (trimmed.includes("ضمان")) {
      return "Full official warranty covering the entire duration with 24/7 dedicated support.";
    }
    return "Follow the official activation instructions delivered with your order to complete setup.";
  }

  return trimmed;
}

